import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readThemeChannels } from '../../client/scripts/brandPalette.mjs';

/**
 * Writes `src/mail/palette.ts` from the light theme block of the client's
 * `src/index.css`.
 *
 * The email layout held six hex literals - a templated indigo and five greys -
 * with nothing tying them to the palette, which is how every transactional
 * email kept rendering `#4f46e5` for two redesigns after the app moved to
 * violet. That is the same defect `brandPalette.mjs` was written to end for the
 * favicons and the OG image, in a second workspace (issue #10).
 *
 * The output is **committed**, and that is forced by the deployment rather than
 * chosen for convenience: `server/Dockerfile` copies `package.json`, the base
 * tsconfig and `server/`, and never `client/src`. The stylesheet simply is not
 * in the server's build context, so a palette resolved at server build time
 * cannot work. Committing the generated file is the same answer, for the same
 * reason, that the favicons are committed rather than built.
 *
 * Re-run with `npm run mail:palette -w server` after changing the palette.
 * `tests/mail.palette.test.ts` fails if the committed file falls behind.
 *
 * The light block is the right source. Email has no `prefers-color-scheme`
 * worth relying on - a message is one fixed document, and the shell is already
 * a light design - so the server renders one theme rather than guessing.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.join(here, '..', 'src', 'mail', 'palette.ts');

/**
 * Which token each drawn part of an email takes its colour from.
 *
 * `brand` and `brandFill` are deliberately separate. The masthead tile and the
 * button are solid blocks carrying white text, which is exactly what
 * `--color-primary-fill` exists for; the detail line in a list is an accent on
 * the surface, which is `--color-primary`'s job. The two hold the same value in
 * the light theme today and different ones in the dark, so mapping them by role
 * rather than by their current value is what keeps this correct if they ever
 * diverge here too.
 */
const SOURCE_TOKENS = {
  brand: 'color-primary',
  brandFill: 'color-primary-fill',
  brandFillText: 'color-primary-fill-fg',
  ink: 'color-text',
  muted: 'color-text-muted',
  border: 'color-border',
  canvas: 'color-canvas',
  surface: 'color-surface',
};

function toHex(channels) {
  return `#${channels
    .split(' ')
    .map((value) => Number(value).toString(16).padStart(2, '0'))
    .join('')}`;
}

function resolve() {
  const channels = readThemeChannels('light');

  return Object.entries(SOURCE_TOKENS).map(([name, token]) => {
    const value = channels[token];

    if (!value) {
      throw new Error(
        `Cannot resolve the mail ${name} colour: --${token} is missing from the light theme ` +
          "block of client/src/index.css. The email palette is drawn from the app's shipped " +
          'tokens, so this has to be fixed rather than defaulted.',
      );
    }

    return [name, token, toHex(value)];
  });
}

function render(entries) {
  const palette = entries.map(([name, , hex]) => `  ${name}: '${hex}',`).join('\n');
  const tokens = entries.map(([name, token]) => `  ${name}: '${token}',`).join('\n');

  return `/**
 * Generated by \`npm run mail:palette -w server\` from the light theme block of
 * \`client/src/index.css\`. Do not edit by hand - re-run the script.
 *
 * Email is rendered server-side and the client's stylesheet is not in the
 * server's build context (\`server/Dockerfile\` never copies \`client/src\`), so
 * this file is generated ahead of time and committed rather than resolved at
 * build time. \`tests/mail.palette.test.ts\` re-reads the stylesheet and fails if
 * these values fall behind it, which is what stops the drift that issue #10
 * recorded: six hex literals here, a palette that moved, and every email
 * shipping a colour the product no longer used.
 */

/** The colours every email and the unsubscribe page are drawn in. */
export const MAIL_PALETTE = {
${palette}
} as const;

/**
 * The token each colour above came from, so the drift test can re-derive them
 * without restating the mapping. A copy of the mapping in the test would be one
 * more thing to keep in step - the failure this file exists to prevent.
 */
export const MAIL_PALETTE_TOKENS = {
${tokens}
} as const;

/** Which theme block the values were read from. Email renders one, fixed. */
export const MAIL_PALETTE_THEME = 'light';
`;
}

const entries = resolve();
await writeFile(outputPath, render(entries), 'utf8');
console.log(`Mail palette written to ${outputPath}`);
for (const [name, token, hex] of entries) console.log(`  ${name.padEnd(14)} --${token} ${hex}`);
