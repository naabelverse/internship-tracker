import { Application } from '@/models/Application';
import {
  ALLOWED_ATTACHMENT_TYPES,
  eraseStoredFiles,
  type FileErasureResult,
} from '@/services/attachment.service';
import type { StorageAdapter, StoredObjectInfo } from '@/storage/StorageAdapter';

/** Every upload lives under this prefix; nothing outside it is ever swept. */
export const ATTACHMENT_PREFIX = 'attachments/';

/**
 * How old an unreferenced object must be before it counts as an orphan.
 * `addAttachment` stores the bytes before it saves the document, so a live
 * upload briefly has no reference. A day is far past any upload in flight.
 */
export const SWEEP_MIN_AGE_MS = 24 * 60 * 60 * 1000;

const extensions = [...new Set(Object.values(ALLOWED_ATTACHMENT_TYPES))].join('|');

/**
 * The exact shape `buildStorageKey` produces: user id, application id, then a
 * v4 UUID with an allowed extension. The application segment comes from the
 * route parameter, so it is allowed in either case.
 */
const GENERATED_KEY = new RegExp(
  `^attachments/[0-9a-f]{24}/[0-9a-fA-F]{24}/` +
    `[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\\.(?:${extensions})$`,
);

/** True when the key is one the app itself would have generated for an upload. */
export function isGeneratedAttachmentKey(key: string): boolean {
  return GENERATED_KEY.test(key);
}

export interface SweepClassification {
  /** A document still points at these. Never touched. */
  referenced: StoredObjectInfo[];
  /** Unreferenced, but young enough to be an upload whose document is not saved yet. */
  recent: StoredObjectInfo[];
  /** Unreferenced and not in the generated shape: something else put them there. */
  unrecognised: StoredObjectInfo[];
  /** Unreferenced, generated by the app and older than the threshold: the only deletable set. */
  orphans: StoredObjectInfo[];
}

/**
 * Sorts listed objects into the four buckets above. A reference wins over
 * every other test, and an object must pass all three to be an orphan.
 */
export function classifyStoredObjects(
  objects: StoredObjectInfo[],
  referencedKeys: ReadonlySet<string>,
  now: Date,
): SweepClassification {
  const result: SweepClassification = { referenced: [], recent: [], unrecognised: [], orphans: [] };
  const cutoff = now.getTime() - SWEEP_MIN_AGE_MS;

  for (const object of objects) {
    if (referencedKeys.has(object.key)) result.referenced.push(object);
    else if (!isGeneratedAttachmentKey(object.key)) result.unrecognised.push(object);
    else if (object.lastModified.getTime() >= cutoff) result.recent.push(object);
    else result.orphans.push(object);
  }

  return result;
}

/**
 * Every storage key an application still references, across all users.
 *
 * Deliberately not scoped by user: the sweep compares one whole bucket with
 * one whole database. It reads only the key field, streamed with a cursor.
 */
export async function collectReferencedKeys(): Promise<Set<string>> {
  const keys = new Set<string>();
  const cursor = Application.find({ 'attachments.0': { $exists: true } })
    .select('attachments.filename')
    .lean()
    .cursor();

  for await (const application of cursor) {
    for (const attachment of application.attachments) keys.add(attachment.filename);
  }

  return keys;
}

export interface SweepPlan extends SweepClassification {
  /** Objects listed under the attachment prefix. */
  listed: number;
  /** Application documents in the database, of any user. */
  applications: number;
}

/** Lists the bucket, reads every reference and classifies. Deletes nothing. */
export async function planSweep(storage: StorageAdapter, now: Date): Promise<SweepPlan> {
  const objects = await storage.list(ATTACHMENT_PREFIX);
  const [referencedKeys, applications] = await Promise.all([
    collectReferencedKeys(),
    Application.countDocuments({}),
  ]);

  return {
    ...classifyStoredObjects(objects, referencedKeys, now),
    listed: objects.length,
    applications,
  };
}

/** A guard stopped `--apply`. Nothing was deleted. */
export class SweepRefusedError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SweepRefusedError';
  }
}

export interface SweepApproval {
  /** The orphan count the operator saw on the dry run. */
  expect?: number;
  allowMajority: boolean;
}

/** More than half of every listed object is an orphan. */
export function isMajority(plan: SweepPlan): boolean {
  return plan.orphans.length * 2 > plan.listed;
}

/**
 * Guards that must all pass before anything is deleted.
 *
 * An empty database makes every file look orphaned, which is also what
 * pointing the script at the wrong MONGO_URI looks like, so it is refused
 * outright. A majority can be legitimate after months of unerased deletions,
 * so it needs an explicit override instead.
 */
export function assertSweepAllowed(plan: SweepPlan, approval: SweepApproval): void {
  if (plan.applications === 0) {
    throw new SweepRefusedError(
      'The database has no applications, so every file would look orphaned. Check MONGO_URI.',
    );
  }

  if (approval.expect === undefined) {
    throw new SweepRefusedError('--apply needs --expect <count>, the orphan count from a dry run.');
  }

  if (approval.expect !== plan.orphans.length) {
    throw new SweepRefusedError(
      `Expected ${String(approval.expect)} orphans but found ${String(plan.orphans.length)}. ` +
        'Run a dry run again and review it.',
    );
  }

  if (isMajority(plan) && !approval.allowMajority) {
    throw new SweepRefusedError(
      `${String(plan.orphans.length)} of ${String(plan.listed)} files are orphans, a majority. ` +
        'Confirm the database is the right one, then pass --allow-majority.',
    );
  }
}

/** Checks every guard, then deletes the orphans and only the orphans. */
export async function applySweep(
  storage: StorageAdapter,
  plan: SweepPlan,
  approval: SweepApproval,
): Promise<FileErasureResult> {
  assertSweepAllowed(plan, approval);

  return eraseStoredFiles(
    plan.orphans.map((object) => object.key),
    storage,
  );
}

export interface OrphanGroup {
  userId: string;
  bytes: number;
  keys: string[];
}

/** Orphans grouped by the user id segment of their key, largest first. */
export function groupOrphansByUser(orphans: StoredObjectInfo[]): OrphanGroup[] {
  const groups = new Map<string, OrphanGroup>();

  for (const object of orphans) {
    const userId = object.key.split('/')[1];
    const group = groups.get(userId) ?? { userId, bytes: 0, keys: [] };
    group.bytes += object.size;
    group.keys.push(object.key);
    groups.set(userId, group);
  }

  return [...groups.values()].sort((a, b) => b.bytes - a.bytes);
}
